L_ref = 10;    % m  — pipe length
eps   = 4.5e-5; % m  — commercial steel roughness



%% ---- Loop over streams ----------------------------------------------
names = {};
data  = [];

for k = 1:size(S,1)
    name   = S{k,1};
    T_C    = S{k,2};
    P_bara = S{k,3};
    n_vec  = cell2mat(S(k,4:11));
    Vmax   = S{k,12};
    dP_al  = S{k,13};
    mu     = S{k,14};

    n_tot = sum(n_vec);

    if n_tot == 0 || P_bara <= 0
        continue
    end

    y_mix  = n_vec ./ n_tot;
    MW_mix = sum(y_mix .* MW_c);
    n_kmol_day = n_tot;

    % ---- CALL FUNCTION ----
    row = PipeDia(P_bara, T_C, n_kmol_day, ...
        y_mix, MW_mix, Tc_K, Pc_Pa, om, ...
        L_ref, Vmax, dP_al, eps, mu);

    names{end+1,1} = name;
    data = [data; row];
end

