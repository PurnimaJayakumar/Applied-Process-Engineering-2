%% DESULPHURIZER ENERGY BALANCE – CORRECT ΔH(T) CALCULATION
% Cp(T) = R*(a + b*T + c*T^2 + d*T^3)

clc; clear;

%% ------------------------------------------------------------------------
% 1. INPUTS
% ------------------------------------------------------------------------

T_oper = 673;     % Operating temperature (K)  -> 400 °C

H2S_kmol_day = 16;                 
H2S_mol_day = H2S_kmol_day * 1000; 
sec_per_day = 86400;
R = 8.314;    % J/mol.K

%% ------------------------------------------------------------------------
% 2. USER Cp/R COEFFICIENTS
% ------------------------------------------------------------------------

coeffs_H2S = [3.931, 1.490e-3, 0, -0.232e5];
coeffs_H2O = [3.470, 1.450e-3, 0, 0.121e5];

coeffs_ZnO = [5.170, 1.10e-3, 0, 0];
coeffs_ZnS = [6.000, 1.20e-3, 0, 0];

%% ------------------------------------------------------------------------
% 3. CP POLYNOMIAL FUNCTIONS
% ------------------------------------------------------------------------

Cp_poly = @(a,T) R*( a(1) + a(2)*T + a(3)*T.^2 + a(4)*T.^3 );

intCp_poly = @(a,T1,T2) R*( a(1)*(T2 - T1) + a(2)*(T2^2 - T1^2)/2 + a(3)*(T2^3 - T1^3)/3 - a(4)*( T2^(-1) - T1^(-1) ));

%% ------------------------------------------------------------------------
% 4. STANDARD REACTION ENTHALPY
% ------------------------------------------------------------------------

dH298 = -118;   % kJ/mol

%% ------------------------------------------------------------------------
% 5. ΔH(T) = ΔH298 + correction from 298 → T_oper
% ------------------------------------------------------------------------

dH_prod = ( intCp_poly(coeffs_ZnS,298,T_oper) + intCp_poly(coeffs_H2O,298,T_oper) ) / 1000;
dH_reac = ( intCp_poly(coeffs_ZnO,298,T_oper) + intCp_poly(coeffs_H2S,298,T_oper) ) / 1000;

dH_T = dH298 + (dH_prod - dH_reac);

%% ------------------------------------------------------------------------
% 6. HEAT DUTY
% ------------------------------------------------------------------------

Q_kJ_day = dH_T * H2S_mol_day;
Q_kW = Q_kJ_day / sec_per_day;

%% ------------------------------------------------------------------------
% 7. PRINT RESULTS
% ------------------------------------------------------------------------

fprintf("\n================ DESULPHURIZER ENERGY =================\n");
fprintf("Operating temperature: %.1f K\n", T_oper);
fprintf("ΔH reaction at T: %.4f kJ/mol\n", dH_T);
fprintf("Total heat release: %.4f kW  |  %e kJ/day\n", Q_kW, Q_kJ_day);
fprintf("========================================================\n\n");
